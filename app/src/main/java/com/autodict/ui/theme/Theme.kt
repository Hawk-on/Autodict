/** Kva tema appen skal bruke. Lagra i innstillingane. */
enum class ThemeMode(val id: String, val displayName: String) {
    SYSTEM("system", "Følg systemet"),
    LIGHT("light", "Lyst"),
    DARK("dark", "Mørkt"),
    ;

    companion object {
        val DEFAULT = SYSTEM

        fun fromId(id: String): ThemeMode = entries.firstOrNull { it.id == id } ?: DEFAULT
    }
}

/**
 * Merk: dynamiske fargar (Material You) er **av**. Dei hentar fargar frå bakgrunnsbiletet,
 * og Google sin mørke variant legg seg nær svart – nettopp det vi vil unngå her. Paletten
 * over er avstemt for lesing, så vi lèt han gjelde i staden for å bli overstyrt av tapetet.
 */
@Composable
fun AutodictTheme(
    themeMode: ThemeMode = ThemeMode.DEFAULT,
    content: @Composable () -> Unit,
) {
    val darkTheme = when (themeMode) {
        ThemeMode.SYSTEM -> isSystemInDarkTheme()
        ThemeMode.LIGHT -> false
        ThemeMode.DARK -> true
    }

    MaterialTheme(
        colorScheme = if (darkTheme) DarkColorScheme else LightColorScheme,
        typography = Typography,
        content = content,
    )
}
